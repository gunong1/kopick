import { AsGrade, Product, ProductSpecs } from "../types";

const CATEGORY_ID = "cat-wireless-vacuum";

type ProductInput = {
  id: string;
  name: string;
  brand: string;
  price: number;
  releaseYear: number;
  specs: ProductSpecs;
  avgRating: number;
  reviewCount: number;
  warrantyMonths: number;
  serviceCenterCount: number;
  asGrade: AsGrade;
  positiveKeywords: string[];
  negativeKeywords: string[];
  summaryText: string;
  dataConfidence?: number;
  imageUrl?: string;
};

// 실제 쇼핑몰 연동 전이므로 retailers.url은 목업 링크다. 실제 연동 시 쿠팡파트너스/네이버 제휴 딥링크로 교체한다.
function makeProduct(input: ProductInput): Product {
  const naverPrice = input.price + Math.round(input.price * 0.012 * (input.id.length % 2 === 0 ? 1 : -1));
  return {
    id: input.id,
    categoryId: CATEGORY_ID,
    name: input.name,
    brand: input.brand,
    price: input.price,
    releaseYear: input.releaseYear,
    imageUrl: input.imageUrl,
    specs: input.specs,
    retailers: [
      {
        name: "coupang",
        label: "쿠팡",
        price: input.price,
        url: `https://www.coupang.com/vp/products/mock-${input.id}`,
        inStock: true,
      },
      {
        name: "naver",
        label: "네이버쇼핑",
        price: naverPrice,
        url: `https://search.shopping.naver.com/mock/${input.id}`,
        inStock: true,
      },
    ],
    reviews: {
      avgRating: input.avgRating,
      reviewCount: input.reviewCount,
      positiveKeywords: input.positiveKeywords,
      negativeKeywords: input.negativeKeywords,
      summaryText: input.summaryText,
    },
    as: {
      warrantyMonths: input.warrantyMonths,
      serviceCenterCount: input.serviceCenterCount,
      grade: input.asGrade,
    },
    dataConfidence: input.dataConfidence ?? (input.reviewCount < 1000 ? 0.75 : 0.95),
  };
}

